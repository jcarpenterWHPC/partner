<?php

namespace App\Commands;

use App\Libraries\EnvFile;
use CodeIgniter\CLI\BaseCommand;
use CodeIgniter\CLI\CLI;

/**
 * Rebuilds .env from AWS Secrets Manager, the box's only source of settings.
 *
 * ⛔ The secret is chosen by the instance role, never by a default, so a box can only
 * ever load its own settings. The new file is written beside .env, read back with
 * CodeIgniter's own parser and compared key by key, and only then replaces .env in one
 * rename. No value is ever printed.
 */
class SecretsRefresh extends BaseCommand
{
  protected $group = 'App';
  protected $name = 'secrets:refresh';
  protected $description = "Rebuild .env from this box's secret in AWS Secrets Manager.";
  protected $usage = 'secrets:refresh [--dry-run]';
  protected $options = ['--dry-run' => 'Fetch, render and verify, list the names that would change, write nothing.'];
  /** Instance role → the one secret that box loads. */
  public const SECRET_FOR_ROLE = [
    'whpc_partner_Production' => 'partner/app-secrets',
    'whpc_partner_test' => 'partner_TEST/app-secrets',
  ];
  public const REQUIRED = ['CI_ENVIRONMENT', 'app.baseURL', 'database.default.hostname', 'database.default.database', 'database.default.username', 'database.default.password', 'encryption.key'];
  public static function secretFor(string $role): ?string
  {
    return self::SECRET_FOR_ROLE[$role] ?? null;
  }
  /**
   * Why $vars must not become this app's .env; empty when they may.
   *
   * @param array<array-key,mixed> $vars
   * @return list<string>
   */
  public static function problems(array $vars): array
  {
    $out = EnvFile::problems($vars);
    foreach (self::REQUIRED as $name)
    {
      if (!isset($vars[$name]) || $vars[$name] === '')
      {
        $out[] = "missing {$name}";
      }
    }
    // Config\Database swaps to the SQLite :memory: tests group under `testing`.
    if (($vars['CI_ENVIRONMENT'] ?? '') === 'testing')
    {
      $out[] = 'CI_ENVIRONMENT is testing, which takes the site off its database';
    }
    return $out;
  }
  public function run(array $params)
  {
    $dry = array_key_exists('dry-run', $params) || CLI::getOption('dry-run') !== null;
    $arn = $this->aws(['sts', 'get-caller-identity', '--query', 'Arn', '--output', 'text']);
    if ($arn === null || !preg_match('#:assumed-role/([^/]+)/#', $arn, $m))
    {
      CLI::error('Cannot tell which instance role this box runs as; refusing.');
      return EXIT_ERROR;
    }
    $secret = self::secretFor($m[1]);
    if ($secret === null)
    {
      CLI::error("No secret is mapped for role {$m[1]}; refusing rather than guessing.");
      return EXIT_ERROR;
    }
    $raw = $this->aws(['secretsmanager', 'get-secret-value', '--secret-id', $secret, '--query', '{s:SecretString,v:VersionId}', '--output', 'json']);
    $got = $raw === null ? null : json_decode($raw, true);
    $vars = is_array($got) && is_string($got['s'] ?? null) ? json_decode($got['s'], true) : null;
    if (!is_array($vars))
    {
      CLI::error("{$secret} is not readable as a JSON object.");
      return EXIT_ERROR;
    }
    $problems = self::problems($vars);
    if ($problems !== [])
    {
      CLI::error("{$secret} cannot become .env:");
      foreach ($problems as $problem)
      {
        CLI::write('  - ' . $problem);
      }
      return EXIT_ERROR;
    }
    $version = (string)($got['v'] ?? '?');
    $env = ROOTPATH . '.env';
    $tmp = ROOTPATH . '.env.refresh-' . getmypid();
    $text = EnvFile::render($vars, [
      "GENERATED by `php spark secrets:refresh` from AWS Secrets Manager {$secret}",
      "(version {$version}, " . date('Y-m-d H:i:s T') . '). Do not edit: change the secret, then run it again.',
    ]);
    if (@file_put_contents($tmp, $text, LOCK_EX) === false)
    {
      CLI::error("Cannot write {$tmp}.");
      return EXIT_ERROR;
    }
    chmod($tmp, is_file($env) ? fileperms($env) & 0777 : 0640);
    if (is_file($env))
    {
      @chgrp($tmp, filegroup($env));
      if (function_exists('posix_geteuid') && posix_geteuid() === 0)
      {
        @chown($tmp, fileowner($env));
      }
    }
    $back = EnvFile::read($tmp);
    $want = array_map('strval', $vars);
    ksort($back);
    ksort($want);
    if ($back !== $want)
    {
      @unlink($tmp);
      $off = array_keys(array_diff_assoc($want, $back) + array_diff_assoc($back, $want));
      CLI::error('Read-back differs from the secret on: ' . implode(', ', $off) . '. .env left as it was.');
      return EXIT_ERROR;
    }
    $old = is_file($env) ? EnvFile::read($env) : [];
    $added = array_keys(array_diff_key($want, $old));
    $removed = array_keys(array_diff_key($old, $want));
    $changed = array_keys(array_filter(array_intersect_key($want, $old), static fn(string $v, string $k): bool => $old[$k] !== $v, ARRAY_FILTER_USE_BOTH));
    CLI::write("{$secret} (version {$version}): " . count($want) . ' settings, read back identically.');
    foreach (['added' => $added, 'changed' => $changed, 'removed' => $removed] as $what => $names)
    {
      CLI::write(sprintf('  %-8s %d%s', $what, count($names), $names === [] ? '' : ': ' . implode(', ', $names)));
    }
    if ($dry)
    {
      @unlink($tmp);
      CLI::write('Dry run: .env not touched.', 'yellow');
      return EXIT_SUCCESS;
    }
    if (!rename($tmp, $env))
    {
      @unlink($tmp);
      CLI::error('Could not move the new file over .env; it is unchanged.');
      return EXIT_ERROR;
    }
    CLI::write('.env rebuilt.', 'green');
    return EXIT_SUCCESS;
  }
  /**
   * The AWS CLI as the instance role: the shared credential files are switched off, and
   * the child gets none of this process's environment, which holds the old .env.
   *
   * @param list<string> $args
   */
  private function aws(array $args): ?string
  {
    $env = [
      'PATH' => getenv('PATH') ? : '/usr/local/bin:/usr/bin:/bin',
      'HOME' => getenv('HOME') ? : sys_get_temp_dir(),
      'AWS_SHARED_CREDENTIALS_FILE' => '/dev/null',
      'AWS_CONFIG_FILE' => '/dev/null',
      'AWS_DEFAULT_REGION' => 'us-east-1',
      'AWS_PAGER' => '',
    ];
    $proc = proc_open(array_merge(['timeout', '30', 'aws'], $args), [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, null, $env);
    if (!is_resource($proc))
    {
      CLI::error('Cannot start the AWS CLI.');
      return null;
    }
    $out = stream_get_contents($pipes[1]);
    $err = stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $rc = proc_close($proc);
    if ($rc !== 0)
    {
      $first = trim((string)strtok((string)$err, "\n"));
      CLI::error('aws ' . $args[0] . ' ' . $args[1] . ': ' . ($first !== '' ? $first : "exit {$rc}"));
      return null;
    }
    return trim((string)$out);
  }
}
